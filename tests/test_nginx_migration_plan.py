    def test_custom_or_additional_compose_overrides_block_future_automation(self):
        variants = (
            ("services:\n  misp-core:\n    ports: [\"8443:443\"]\n", None),
            (LEGACY_OVERRIDE, ("compose.override.yaml", "services: {}\n")),
        )
        for override, extra in variants:
            with self.subTest(extra=extra), tempfile.TemporaryDirectory() as td:
                install = make_install(Path(td), [
                    "BASE_URL=https://misp.example.com",
                    "CORE_HTTP_PORT=127.0.0.1:8080",
                    "CORE_HTTPS_PORT=127.0.0.1:8443",
                ], override=override)
                if extra:
                    (install / extra[0]).write_text(extra[1])
                result = run_plan(install)
                self.assertEqual(result.returncode, 2)
                plan = json.loads(result.stdout)
                self.assertEqual(plan["compose_override"], "custom_or_multiple")
                self.assertIn("custom_compose_override", plan["blockers"])

