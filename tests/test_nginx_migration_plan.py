    def test_mixed_incomplete_and_unrecognized_layouts_are_distinct(self):
        cases = {
            "mixed": [
                "BASE_URL=https://misp.example.com",
                "CORE_HTTP_PORT=80", "CORE_HTTPS_PORT=443", "NGINX_HTTP_PORT=80",
            ],
            "incomplete": ["BASE_URL=https://misp.example.com", "CORE_HTTP_PORT=80"],
            "ambiguous": ["BASE_URL=https://misp.example.com", "ADMIN_PASSWORD=secret"],
        }
        for expected, lines in cases.items():
            with self.subTest(expected=expected), tempfile.TemporaryDirectory() as td:
                install = make_install(Path(td), lines)
                result = run_plan(install)
                self.assertEqual(result.returncode, 2, result.stderr)
                plan = json.loads(result.stdout)
                self.assertEqual(plan["classification"], expected)
                self.assertEqual(plan["disposition"], "manual_review_required")
                self.assertTrue(plan["blockers"])
                self.assertNotIn("secret", result.stdout + result.stderr)

